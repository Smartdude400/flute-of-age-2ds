"""Translate KanjiTex_CodepointToOffset (src/code/kanji_tex.s: hand-written MIPS, Shift-JIS codepoint ->
kanji texture offset) into C. The function follows the equivalent C given in the original file's comment;
the lookup table (low_codepoints_lookup_table, 7 x 0xBC big-endian halfwords) is read from the ROM's
`code` file. Output: source/game/code/kanji_tex.c"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE_OFFSET = 0x9E788  # low_codepoints_lookup_table in `code` (NTSC 1.0)
N = 7 * 0xBC
code = RomFS("ntsc-1.0").get("code")
nums = ["0x%04X" % v for v in struct.unpack_from(">%dH" % N, code, TABLE_OFFSET)]
out = ["// GENERATED by tools/gen_kanji_tex.py from the ROM (translation of src/code/kanji_tex.s; do not edit)",
       '#include "kanji_tex.h"', '#include "message_data_fmt.h"', "",
       "static const s16 low_codepoints_lookup_table[7 * 0xBC] = {"]
for i in range(0, len(nums), 16):
    out.append("    " + ", ".join(nums[i:i + 16]) + ",")
out += ["};", "",
        "s32 KanjiTex_CodepointToOffset(s32 codepoint) {",
        "    s32 i;", "",
        "    if (codepoint < 0x8800) {",
        "        i = (codepoint & 0xFF) - 0x40;",
        "        if (i >= 0x40) {", "            i -= 1;", "        }",
        "        i += ((codepoint >> 8) - 0x81) * 0xBC;",
        "        return low_codepoints_lookup_table[i] * 128; // FONT_CHAR_TEX_SIZE",
        "    } else {",
        "        i = (codepoint & 0xFF) - 0x40;",
        "        if (i >= 0x40) {", "            i -= 1;", "        }",
        "        i += 0x30A;",
        "        i += ((codepoint >> 8) - 0x88) * 0xBC;",
        "        return i * 128; // FONT_CHAR_TEX_SIZE",
        "    }", "}"]
with open(os.path.join(HERE, "..", "source", "game", "code", "kanji_tex.c"), "w", newline="") as fh:
    fh.write("\n".join(out) + "\n")
print("kanji_tex.c:", N, "entries")
