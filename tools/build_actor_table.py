"""Original actor-overlay memory sizes (text+data+rodata+bss) from the ROM's overlay relocation
trailers, so the native actor table can reserve exactly the same actor-heap memory when an actor's
code "loads" (the code itself is statically linked on DS). Output:
source/game/code/actor_overlay_sizes.inc.h"""
import os, re, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS

HERE = os.path.dirname(os.path.abspath(__file__))
TABLE = os.path.join(HERE, "..", "source", "game", "include", "tables", "actor_table.h")
OUT = os.path.join(HERE, "..", "source", "game", "code", "actor_overlay_sizes.inc.h")
fs = RomFS("ntsc-1.0")
lines = ["// GENERATED by tools/build_actor_table.py: original overlay memory sizes (text+data+rodata+bss)"]
n = 0
for m in re.finditer(r"DEFINE_ACTOR\((\w+),\s*(\w+),", open(TABLE, encoding="utf-8").read()):
    name, enum = m.group(1), m.group(2)
    f = "ovl_" + name
    if f not in fs.entries:
        continue
    d = fs.get(f)
    off = struct.unpack_from(">I", d, len(d) - 4)[0]
    text, data, rodata, bss = struct.unpack_from(">IIII", d, len(d) - off)
    lines.append(f"[{enum}] = 0x{text + data + rodata + bss:X}, // {name}: text {text:#x} data {data:#x} rodata {rodata:#x} bss {bss:#x}")
    n += 1
open(OUT, "w", newline="\n").write("\n".join(lines) + "\n")
print(n, "overlay sizes")

# ---- effect soft-sprite overlays (same treatment)
ETABLE = os.path.join(HERE, "..", "source", "game", "include", "tables", "effect_ss_table.h")
EOUT = os.path.join(HERE, "..", "source", "game", "code", "effect_ss_overlay_sizes.inc.h")
lines = ["// GENERATED by tools/build_actor_table.py: original effect overlay memory sizes"]
for m in re.finditer(r"DEFINE_EFFECT_SS\((\w+),\s*(\w+)\)", open(ETABLE, encoding="utf-8").read()):
    name, enum = m.group(1), m.group(2)
    f = "ovl_" + name
    if f not in fs.entries:
        continue
    d = fs.get(f)
    off = struct.unpack_from(">I", d, len(d) - 4)[0]
    text, data, rodata, bss = struct.unpack_from(">IIII", d, len(d) - off)
    lines.append(f"[{enum}] = 0x{text + data + rodata + bss:X}, // {name}")
open(EOUT, "w", newline="\n").write("\n".join(lines) + "\n")
print(len(lines) - 1, "effect overlay sizes")

# ---- other code overlays loaded by game code into game-arena memory (sizes only)
MOUT = os.path.join(HERE, "..", "source", "game", "include", "misc_overlay_sizes.h")
lines = ["// GENERATED by tools/build_actor_table.py: original memory sizes of non-actor code overlays",
         "#pragma once"]
for name in ("ovl_map_mark_data", "ovl_kaleido_scope", "ovl_player_actor", "ovl_file_choose", "ovl_select",
             "ovl_title", "ovl_opening", "ovl_end_title", "ovl_fbdemo_triforce", "ovl_fbdemo_wipe1",
             "ovl_fbdemo_wipe3", "ovl_fbdemo_wipe4", "ovl_fbdemo_wipe5"):
    if name not in fs.entries:
        continue
    d = fs.get(name)
    off = struct.unpack_from(">I", d, len(d) - 4)[0]
    text, data, rodata, bss = struct.unpack_from(">IIII", d, len(d) - off)
    lines.append(f"#define OVL_SIZE_{name[4:].upper()} 0x{text + data + rodata + bss:X}")
open(MOUT, "w", newline="\n").write("\n".join(lines) + "\n")
print(len(lines) - 2, "misc overlay sizes")
