"""Native segment_symbols.h: the original linker symbols _<file>SegmentRomStart/RomEnd become
constants equal to the file's ROM address range (from the ROM's DMA table). In the DS port they
serve as file identifiers (converted files are named by their ROM start address) and sizes.
RAM-segment symbols (_<file>SegmentStart/End of code/overlay segments) are not provided."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "source", "game", "include", "segment_symbols.h")
fs = RomFS("ntsc-1.0")
lines = ["// GENERATED by tools/gen_segment_symbols.py (rewritten: native). See the generator for meaning.",
         "#ifndef SEGMENT_SYMBOLS_H", "#define SEGMENT_SYMBOLS_H", "#include <stdint.h>", "",
         "#define DECLARE_SEGMENT(name)", "#define DECLARE_ROM_SEGMENT(name)", "#define DECLARE_BSS_SEGMENT(name)",
         "#define DECLARE_OVERLAY_SEGMENT(name)", ""]
for name, (vs, ve, rs, re_) in fs.entries.items():
    if not name.isidentifier():
        continue
    lines.append(f"#define _{name}SegmentRomStart ((uint8_t*)0x{vs:08X})")
    lines.append(f"#define _{name}SegmentRomEnd ((uint8_t*)0x{ve:08X})")
lines += ["", "#endif", ""]
open(OUT, "w", newline="\n").write("\n".join(lines))
print(len(fs.entries), "files")
