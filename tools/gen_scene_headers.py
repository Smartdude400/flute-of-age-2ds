"""Symbol headers (asset handles only, no data conversion) for every scene referenced by game code
via `#include "assets/scenes/<group>/<scene>/<file>.h"`. Data is converted per scene by
build_scene.py when that scene is actually used."""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xmlspec
from romfs import RomFS

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..", "source", "game")
INC = os.path.join(GAME, "include")
AGG = os.path.join(GAME, "assets_agg")
TOKEN = 0x80000000
pat = re.compile(r'#include\s+"(assets/scenes/[^/]+/([^/"]+)/([^/"]+)\.h)"')
fs = RomFS("ntsc-1.0")
done = 0
seen = set()
for dp, _, files in os.walk(GAME):
    for f in files:
        if not f.endswith((".c", ".h")):
            continue
        for m in pat.finditer(open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()):
            inc, scene, fname = m.groups()
            if inc in seen:
                continue
            seen.add(inc)
            try:
                spec = xmlspec.load(scene)
            except FileNotFoundError:
                print("no xml for", scene)
                continue
            lines = [f"// GENERATED by tools/gen_scene_headers.py: asset handles of scene {scene}",
                     f"#ifndef ASSET_SCENE_{scene.upper()}_{fname.upper()}_H",
                     f"#define ASSET_SCENE_{scene.upper()}_{fname.upper()}_H", '#include "asset_token.h"']
            for file_name, fspec in spec.items():
                seg = fspec["segment"]
                for tag, sym, off, attrs in fspec["symbols"]:
                    if tag in ("Scene", "Room"):
                        continue  # file-level symbols (scene/room file names) are not handles
                    lines.append(f"#define {sym} ASSET_TOKEN(0x{TOKEN | (seg << 24) | off:08X}) // {tag} in {file_name}")
            lines.append("#endif\n")
            path = os.path.join(INC, inc)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", newline="\n").write("\n".join(lines))
            done += 1
print(done, "scene headers")
