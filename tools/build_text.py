"""Message text converter (closes stub S9).

The original build generates the message table from text sources. Here everything is recovered
from the ROM:
  - the three message entry tables in the `code` file (JPN: segment 0x08, NES: 0x07, staff: 0x07),
    found by their shape ({u16 textId, u8 typePos, u8 0, u32 segmentAddress} ..., textId 0xFFFF);
  - the message bytes: the three *_message_data_static files are copied to romfs/vrom/<vrom>.bin.
    The bytes are the game's own text encoding (control codes included); they are decoded at run time
    by the translated game logic (Message_Decode), exactly as in the original.
Outputs:
  source/game/include/text/message_data.h        DEFINE_MESSAGE_JPN / _NES entries (table order)
  source/game/include/text/message_data_staff.h  credits entries
  source/game/include/text/message_symbols.h     _message_<id>_<lang> = original segment addresses
usage: python tools/build_text.py"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, "..", "source", "game", "include", "text")
ROMFS = os.path.join(HERE, "..", "romfs", "vrom")


def find_tables(code):
    def walk(off):
        rows, o, last = [], off, -1
        while o + 8 <= len(code):
            t, tp, pad, s = struct.unpack_from(">HBBI", code, o)
            if t == 0xFFFF:
                return rows
            if pad != 0 or (s >> 24) not in (7, 8) or s < last:
                return None
            rows.append((t, tp, s))
            last = s
            o += 8
        return None

    found, off = [], 0
    while off < len(code) - 8:
        t, tp, pad, s = struct.unpack_from(">HBBI", code, off)
        if pad == 0 and (s & 0xFFFFFF) == 0 and (s >> 24) in (7, 8):
            rows = walk(off)
            if rows and len(rows) > 5:
                found.append(rows)
                off += 8 * (len(rows) + 1)
                continue
        off += 4
    return found


def main():
    fs = RomFS("ntsc-1.0")
    tables = find_tables(fs.get("code"))
    assert len(tables) == 3, [len(t) for t in tables]
    jpn, nes, staff = tables  # order in the code file: JPN, NES, staff
    assert jpn[0][2] >> 24 == 8 and nes[0][2] >> 24 == 7 and staff[0][0] == 0x0500
    # the last two JPN entries are 0xFFFC, 0xFFFD and the last NES entry is 0xFFFD; those are defined by
    # assets/text/message_data.h itself, so they are left out of the generated list.
    assert [r[0] for r in jpn[-2:]] == [0xFFFC, 0xFFFD], [hex(r[0]) for r in jpn[-2:]]
    assert nes[-1][0] == 0xFFFD, hex(nes[-1][0])

    os.makedirs(INC, exist_ok=True)
    lines = ["// GENERATED by tools/build_text.py from the ROM message tables (do not edit).",
             "// Message contents are not needed here: the table only records id, box type/position and",
             "// the message's original segment address (text/message_symbols.h)."]
    for t, tp, s in jpn[:-2]:
        lines.append(f"DEFINE_MESSAGE_JPN(0x{t:04X}, {tp >> 4}, {tp & 0xF}, , , , )")
    for t, tp, s in nes[:-1]:
        lines.append(f"DEFINE_MESSAGE_NES(0x{t:04X}, {tp >> 4}, {tp & 0xF}, , , , )")
    open(os.path.join(INC, "message_data.h"), "w", newline="\n").write("\n".join(lines) + "\n")

    lines = ["// GENERATED by tools/build_text.py (credits message table)."]
    for t, tp, s in staff:
        lines.append(f"DEFINE_MESSAGE(0x{t:04X}, {tp >> 4}, {tp & 0xF}, )")
    open(os.path.join(INC, "message_data_staff.h"), "w", newline="\n").write("\n".join(lines) + "\n")

    sym = ["// GENERATED by tools/build_text.py: message symbols = original segment addresses.",
           "#pragma once",
           "#define _jpn_message_data_staticSegmentStart ((const char*)0x08000000)",
           "#define _nes_message_data_staticSegmentStart ((const char*)0x07000000)",
           "#define _staff_message_data_staticSegmentStart ((const char*)0x07000000)"]
    for rows, lang in ((jpn, "jpn"), (nes, "nes"), (staff, "staff")):
        for t, tp, s in rows:
            sym.append(f"#define _message_0x{t:04X}_{lang} ((const char*)0x{s:08X})")
    open(os.path.join(INC, "message_symbols.h"), "w", newline="\n").write("\n".join(sym) + "\n")

    os.makedirs(ROMFS, exist_ok=True)
    for name in ("jpn_message_data_static", "nes_message_data_static", "staff_message_data_static"):
        vrom = fs.entries[name][0]
        data = fs.get(name)
        if name.startswith("jpn"):
            # Japanese text is read in 16-bit units only (Font.msgBufWide, z_message.c / z_kanfont.c): stored
            # in native byte order. NES / staff text is read byte by byte and stays as it is.
            n = len(data) // 2
            data = struct.pack(f"<{n}H", *struct.unpack(f">{n}H", data[:n * 2])) + data[n * 2:]
        open(os.path.join(ROMFS, f"{vrom:08X}.bin"), "wb").write(data)
    print(f"text: jpn {len(jpn)} nes {len(nes)} staff {len(staff)} entries")


main()
