"""Satisfy `#include "assets/<kind>/<file>/<anything>.h"` in adapted game code.

For every such include found under source/game, the referenced ROM file (named by <file>) is
converted with build_object.py (if not done yet), and a thin header is generated at the include
path that includes the per-file asset-handle header (assets/<file>.h). Run after importing sources.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_object
import xmlspec
from romfs import RomFS

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..", "source", "game")
INC = os.path.join(GAME, "include")
AGG = os.path.join(GAME, "assets_agg")

pat = re.compile(r'#include\s+"(assets/(objects|textures|scenes/[^/]+|misc|overlays)/([^/"]+)/[^"]+\.h)"')
needed = {}
for dp, _, files in os.walk(GAME):
    for f in files:
        if f.endswith((".c", ".h")):
            for m in pat.finditer(open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()):
                needed[m.group(1)] = m.group(3)

fs = RomFS("ntsc-1.0")
report = []
built = set(os.path.splitext(n)[0] for n in os.listdir(AGG)) if os.path.isdir(AGG) else set()
for inc, fname in sorted(needed.items()):
    if fname not in built:
        if xmlspec.find_xml(fname) is None or fname not in fs.entries:
            report.append(f"SKIP {inc}: no xml/rom file '{fname}'")
            continue
        try:
            build_object.build(fs, fname, report)
            built.add(fname)
        except Exception as e:  # noqa: BLE001 - report and continue
            report.append(f"FAIL build {fname}: {e}")
            continue
    path = os.path.join(INC, inc)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n") as fh:
        fh.write(f"// GENERATED by tools/gen_asset_headers.py: asset handles of {fname}\n"
                 f'#include "../assets/{fname}.h"\n'.replace("../assets/", "assets_agg/"))
print("\n".join(report))
print(f"{len(needed)} asset includes, {len(built)} files converted")
