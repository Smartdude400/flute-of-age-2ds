"""Generate source/game/code/z_rcp.c: native versions of the original render-state preset helpers
(Gfx_SetupDL_<N><Opa|Xlu|Overlay>(gfxCtx) and func_80093C80) from flute-of-age/src/code/z_rcp.c. Each helper
sends preset list N to one buffer -> Gfx3D_SetupDLTo(buffer, N)."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "..", "..", "flute-of-age", "src", "code", "z_rcp.c"), encoding="utf-8").read()
BUF = {"POLY_OPA_DISP": "GFX_BUF_OPA", "POLY_XLU_DISP": "GFX_BUF_XLU", "OVERLAY_DISP": "GFX_BUF_OVL"}
out = ["// rewritten: native (generated by tools/gen_rcp.py from flute-of-age/src/code/z_rcp.c)",
       "// The original's render-state preset helpers: each sends one preset list (sSetupDL[N]) to one of the",
       "// display-list buffers. Presets are compiled offline (romfs/setupdl.pobj); colour-dither changes that some",
       "// helpers add have no PICA200 equivalent (the 2DS framebuffer is RGBA8, no dithering).",
       '#include "gfx.h"', '#include "gfx_setupdl.h"', '#include "play_state.h"', '#include "engine/gfx3d.h"', ""]
for m in re.finditer(r"^void (Gfx_SetupDL_\w+)\(GraphicsContext\* gfxCtx\) \{(.*?)^\}", src, re.M | re.S):
    calls = re.findall(r"gSPDisplayList\((\w+)\+\+, sSetupDL\[SETUPDL_(\d+)\]\)", m.group(2))
    if not calls:
        continue
    out += [f"void {m.group(1)}(GraphicsContext* gfxCtx) {{", "    (void)gfxCtx;"]
    out += [f"    Gfx3D_SetupDLTo({BUF[b]}, {int(n)});" for b, n in calls]
    out.append("}\n")
out.append("void func_80093C80(PlayState* play) {\n    Gfx_SetupDL_25Opa(play->state.gfxCtx); // + colour dither off in prerendered rooms\n}\n")
open(os.path.join(HERE, "..", "source", "game", "code", "z_rcp.c"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print("z_rcp.c generated")
