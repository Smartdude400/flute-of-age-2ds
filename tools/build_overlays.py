"""Build the display lists embedded in actor overlays (romfs/ovl/ovldata.pobj) + symbol headers.

  python tools/build_overlays.py [ovl_En_Holl ovl_En_Kanban ...]   (default: every overlay XML)

A few actors keep small vertex arrays and display lists in their own .data (the room-transition
plane of En_Holl, the signpost shadow of En_Kanban, ...). Their XML offsets are relative to where
that block sits inside the overlay's data, which depends on the original source order, so the block
base is recovered by self-consistency: the base at which every listed DList is a well-formed list
(ends with G_ENDDL) and the vertex loads point at the listed vertex arrays (at their original VRAM
address, taken from the actor overlay table in code).

Handles are the original VRAM addresses (TOKEN bit + segment nibble 0); the native engine binds
this container as segment 0 (engine/asset.c). Outputs:
  romfs/ovl/ovldata.pobj                       one container for all overlays, meshes keyed by VRAM
  source/game/assets_agg/<ovl_Name>.h   symbol -> handle (thin include header: gen_asset_headers.py)
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS  # noqa: E402
import xmlspec  # noqa: E402
import dl2pica  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "romfs", "ovl")
OUT_HDR = os.path.join(HERE, "..", "source", "game", "assets_agg")
OVERLAY_XML = os.path.join(xmlspec.XML_ROOT, "overlays")


class VramMem:
    """Overlay images placed at their VRAM addresses; DLCompiler reads them as segment 0x80."""
    def __init__(self):
        self.ranges = []  # (start offset in 0x80 segment, bytes)

    def add(self, vram, data):
        self.ranges.append((vram & 0xFFFFFF, data))

    def __getitem__(self, sl):
        for start, data in self.ranges:
            if start <= sl.start < start + len(data):
                return data[sl.start - start:sl.stop - start]
        return b""


def vram_of(fs, code, name):
    vs, ve = fs.entries[name][:2]
    e = code.find(struct.pack(">II", vs, ve))
    while e >= 0 and e % 4:
        e = code.find(struct.pack(">II", vs, ve), e + 1)
    if e < 0:
        return None
    return struct.unpack_from(">II", code, e + 8)


def dl_ok(data, off):
    """A well-formed list: valid-looking commands up to G_ENDDL within 1024 commands."""
    for k in range(1024):
        p = off + 8 * k
        if p + 8 > len(data):
            return False
        if data[p] == 0xDF:
            return True
        if data[p] == 0x00 and k == 0:
            return False
    return False


def find_base(data, vram, symbols):
    dls = [off for tag, sym, off, a in symbols if tag == "DList"]
    arrays = {off for tag, sym, off, a in symbols if tag == "Array"}
    if not dls:
        return None
    cands = []
    for p in range(0, len(data) - 8, 8):
        w0, w1 = struct.unpack_from(">II", data, p)
        if w0 >> 24 == 0x01 and vram <= w1 < vram + len(data):
            for a in arrays or {0}:
                cands.append(w1 - vram - a)
    for base in sorted(set(cands)) or range(0, len(data), 8):
        if base >= 0 and all(dl_ok(data, base + off) for off in dls):
            return base
    return None


def main():
    fs = RomFS("ntsc-1.0")
    code = fs.get("code")
    names = sys.argv[1:] or sorted(f[:-4] for f in os.listdir(OVERLAY_XML) if f.endswith(".xml"))
    mem = VramMem()
    segs = {0x80: mem, 4: fs.get("gameplay_keep")}
    warns = []
    comp = dl2pica.DLCompiler(segs, warn=warns.append)
    meshes = {}
    os.makedirs(OUT_HDR, exist_ok=True)
    for name in names:
        spec = xmlspec.load(name)
        if name not in spec or name not in fs.entries:
            print(f"{name}: no xml/file")
            continue
        vr = vram_of(fs, code, name)
        if vr is None:
            print(f"{name}: not in the actor overlay table")
            continue
        vram = vr[0]
        data = fs.get(name)
        symbols = spec[name]["symbols"]
        base = find_base(data, vram, symbols)
        if base is None:
            print(f"{name}: data block not located")
            continue
        mem.add(vram, data)
        lines = [f"// GENERATED by tools/build_overlays.py for {name}: data embedded in the overlay, as handles",
                 "// (original VRAM addresses, resolved against /ovl/ovldata.pobj bound as segment 0).",
                 f"#ifndef ASSET_{name.upper()}_H", f"#define ASSET_{name.upper()}_H", '#include "asset_token.h"', ""]
        unsup0, w_start, ovl_meshes, n = dict(comp.unsupported), len(warns), {}, 0
        for tag, sym, off, attrs in symbols:
            addr = vram + base + off
            lines.append(f"#define {sym} ASSET_TOKEN(0x{addr:08X}) // {tag}")
            if tag == "DList":
                n += 1
                try:
                    ovl_meshes[addr & 0x0FFFFFFF] = comp.compile(addr)
                except (KeyError, RuntimeError, IndexError, ValueError, struct.error) as e:
                    warns.append(f"{name} DL {sym}: {e}")
        new_unsup = {k: v - unsup0.get(k, 0) for k, v in comp.unsupported.items() if v != unsup0.get(k, 0)}
        if len(warns) != w_start or any(k.startswith("op") for k in new_unsup):
            # a wrong block base decodes data as commands: reject the whole overlay rather than ship garbage
            print(f"{name}: rejected ({len(warns) - w_start} warnings, unsupported {new_unsup})")
            continue
        meshes.update(ovl_meshes)
        lines.append("#endif\n")
        open(os.path.join(OUT_HDR, name + ".h"), "w", newline="\n").write("\n".join(lines))
        print(f"{name}: vram {vram:08X} block @+{base:X}, {n} lists, unsupported {new_unsup or '-'}")
    os.makedirs(OUT, exist_ok=True)
    obj = dl2pica.build_pobj(comp.textures, sorted(meshes.items()))
    open(os.path.join(OUT, "ovldata.pobj"), "wb").write(obj)
    print(f"ovldata.pobj: {len(meshes)} meshes, {len(comp.textures)} textures, {len(obj)} bytes, "
          f"unsupported={comp.unsupported}")
    for w in warns[:20]:
        print("   warn:", w)


main()
