"""Data arrays kept in code overlays -> the `.inc.c` files the game sources include (like the original build,
which extracted them from the ROM). Generated at setup, never committed.

  python tools/build_overlay_data.py

Every `#include "assets/overlays/<ovl>/<symbol>.inc.c"` in source/game is served from the overlay's XML
(tools/assets_xml/overlays) and the overlay file in the ROM. The XML offsets are relative to the data block
of the source file that defines the arrays; the block is located inside the overlay's data section by
self-consistency: every vertex array must decode as plausible vertices (flag 0, coordinates within the
screen range). Only a unique match is accepted.
  Vtx  -> { { { x, y, z }, flag, { s, t }, { r, g, b, a } } },   (engine/vtx.h, native byte order)
  s16 / u16 / s8 / u8 scalars -> numbers
Output: source/game/include/assets/overlays/<ovl>/<symbol>.inc.c
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from romfs import RomFS  # noqa: E402
import xmlspec  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.join(HERE, "..", "source", "game")
OUT = os.path.join(GAME, "include", "assets", "overlays")
SCALAR = {"s16": ">h", "u16": ">H", "s8": ">b", "u8": ">B", "s32": ">i", "u32": ">I"}


def wanted():
    pat = re.compile(r'#include "assets/overlays/(ovl_\w+)/(\w+)\.inc\.c"')
    out = {}
    for dp, _, files in os.walk(GAME):
        for f in files:
            if f.endswith(".c"):
                for m in pat.finditer(open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()):
                    out.setdefault(m.group(1), set()).add(m.group(2))
    return out


def elem(attrs_el):
    tag, sym, off, a = attrs_el
    return a


def locate(data, symbols, start, end):
    vtx = [(off, int(a["Count"], 0)) for tag, sym, off, a in symbols if tag == "Array" and a.get("_elem") == "Vtx"]
    span = max(off + array_size(a) for tag, sym, off, a in symbols if tag == "Array")
    hits = []
    for base in range(start, end - span + 1, 8):
        ok = bool(vtx)
        for off, n in vtx:
            for i in range(n):
                x, y, z, flag = struct.unpack_from(">hhhH", data, base + off + 16 * i)
                if flag != 0 or max(abs(x), abs(y), abs(z)) > 1000:
                    ok = False
                    break
            if not ok:
                break
        if ok:
            hits.append(base)
    return hits


def array_size(a):
    n = int(a["Count"], 0)
    if a.get("_elem") == "Vtx":
        return 16 * n
    return struct.calcsize(SCALAR[a.get("_type", "s16")]) * n


def main():
    fs = RomFS("ntsc-1.0")
    for ovl, syms in sorted(wanted().items()):
        spec = xmlspec.load(ovl)[ovl]["symbols"]
        # element kind of each array, from the XML child element
        import xml.etree.ElementTree as ET
        tree = ET.parse(xmlspec.find_xml(ovl))
        kinds = {}
        for el in tree.iter("Array"):
            child = next(iter(el), None)
            kinds[el.get("Name")] = (child.tag if child is not None else "", child.get("Type", "s16") if child is not None else "")
        for tag, sym, off, a in spec:
            if sym in kinds:
                a["_elem"], a["_type"] = kinds[sym]
        data = fs.get(ovl)
        tail = struct.unpack_from(">I", data, len(data) - 4)[0]
        text, dsize = struct.unpack_from(">II", data, len(data) - tail)
        hits = locate(data, spec, text, text + dsize)
        if len(hits) != 1:
            print(f"{ovl}: data block not located uniquely ({[hex(h) for h in hits][:4]})")
            continue
        base = hits[0]
        os.makedirs(os.path.join(OUT, ovl), exist_ok=True)
        for tag, sym, off, a in spec:
            if sym not in syms or tag != "Array":
                continue
            n = int(a["Count"], 0)
            lines = []
            if a.get("_elem") == "Vtx":
                for i in range(n):
                    x, y, z, flag, s, t, r, g, b, al = struct.unpack_from(">hhhHhhBBBB", data, base + off + 16 * i)
                    lines.append(f"{{ {{ {{ {x}, {y}, {z} }}, {flag}, {{ {s}, {t} }}, {{ {r}, {g}, {b}, {al} }} }} }},")
            else:
                fmt = SCALAR[a.get("_type", "s16")]
                sz = struct.calcsize(fmt)
                vals = [struct.unpack_from(fmt, data, base + off + sz * i)[0] for i in range(n)]
                lines.append(", ".join(str(v) for v in vals) + ",")
            open(os.path.join(OUT, ovl, sym + ".inc.c"), "w", newline="\n").write(
                f"// GENERATED by tools/build_overlay_data.py from {ovl} (ROM data, not committed)\n" + "\n".join(lines) + "\n")
        print(f"{ovl}: data block @+{base:X}, {len(syms)} arrays")


main()
